// Regenerates supabase/functions/api/routes.generated.ts from the files under api/routes. Run: node scripts/gen-router.mjs
import fs from "node:fs"; import path from "node:path";
const base = path.resolve("supabase/functions/api/routes");
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const files = walk(base).filter((f) => f.endsWith("/route.ts")).map((f) => path.relative(base, f).split(path.sep).join("/"));
const entries = files.map((f, i) => {
  const segs = f.replace(/\/route\.ts$/, "").split("/").map((s) => (s.startsWith("[") ? `:${s.slice(1, -1)}` : s));
  return { f, i, pattern: "/" + segs.join("/"), params: segs.filter((s) => s.startsWith(":")).length };
}).sort((a, b) => a.params - b.params || b.pattern.length - a.pattern.length);
let out = "// GENERATED by scripts/gen-router.mjs. Do not edit by hand.\n";
entries.forEach((e) => (out += `import * as r${e.i} from "./routes/${e.f}";\n`));
out += "\nexport type Handler = (req: Request, ctx: { params: Record<string, string> }) => Promise<Response>;\n";
out += "export const ROUTES: { pattern: string; module: Partial<Record<\"GET\" | \"POST\" | \"PUT\" | \"DELETE\", Handler>> }[] = [\n";
entries.forEach((e) => (out += `  { pattern: "${e.pattern}", module: r${e.i} as never },\n`));
out += "];\n";
fs.writeFileSync("supabase/functions/api/routes.generated.ts", out);
console.log(`${entries.length} routes`);
